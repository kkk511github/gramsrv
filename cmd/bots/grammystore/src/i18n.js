export function normalizeLanguage(value, fallback = "zh") {
  const language = String(value ?? "").toLowerCase();
  if (language.startsWith("zh")) return "zh";
  if (language.startsWith("ru")) return "ru";
  if (language.startsWith("en")) return "en";
  return supportedLanguages.includes(fallback) ? fallback : "zh";
}

export function translate(language, key, variables = {}) {
  const normalized = normalizeLanguage(language);
  const template = messages[normalized][key] ?? messages.en[key];
  if (template === undefined) throw new Error(`missing translation key: ${key}`);
  return template.replace(/\{([a-zA-Z0-9_]+)\}/g, (match, name) => variables[name] === undefined ? match : String(variables[name]));
}

const errorTranslations = Object.freeze([
  [/daily spin limit reached/i, "errorDailySpin"],
  [/weekly spin limit reached/i, "errorWeeklySpin"],
  [/finish the pending spin/i, "errorPendingSpin"],
  [/campaign is unavailable/i, "errorCampaignUnavailable"],
  [/campaign limit reached/i, "errorCampaignLimit"],
  [/already claimed/i, "errorAlreadyClaimed"],
  [/sale not found/i, "errorSaleMissing"],
  [/already refunded/i, "errorAlreadyRefunded"],
  [/ticket not found|reply is empty/i, "errorTicketMissing"],
  [/username/i, "errorInvalidUsername"],
  [/amount must be from 1 to 99999/i, "errorStarsRange"],
  [/invalid .*id|invalid id/i, "errorInvalidID"],
  [/invalid .*amount|invalid rate|invalid invoice/i, "errorInvalidAmount"],
  [/product .*exists|product not found/i, "errorProductMissing"],
]);

export function translateError(language, error) {
  const detail = String(error?.message ?? error ?? "");
  const match = errorTranslations.find(([pattern]) => pattern.test(detail));
  return translate(language, match?.[1] ?? "genericError");
}
